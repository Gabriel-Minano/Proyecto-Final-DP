    public int pedirID() {
        try {
            int dato = Integer.parseInt(JOptionPane.showInputDialog(null, "Ingrese una ID:", "Info", JOptionPane.INFORMATION_MESSAGE));
            if (dato == 0) {
                mostrarMensaje("Esa ID no es válida");
            }
            return dato;
        } catch (NumberFormatException e) {
            e.getMessage();
        }
        return 0;
    }

